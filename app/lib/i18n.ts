/**
 * Every user-facing string in one place.
 *
 * The app previously kept four independent dictionaries — one embedded in
 * AuthContext, one in HeroSection, one in the restaurants page, one in the
 * About page — plus a few hundred sentences written straight into JSX. So
 * switching to English translated the header and the section titles and left
 * the chat, the restaurant detail page, the review panels, the footer and every
 * toast in Vietnamese. Collecting them here is what makes "switch language"
 * mean the whole interface rather than the parts somebody remembered.
 *
 * `vi` is the source of truth for the shape: `Dict` is derived from it, so a key
 * added to Vietnamese and forgotten in English is a type error rather than a
 * sentence that silently stays Vietnamese on the English site.
 */

export type Lang = "vi" | "en";

/** Accepts the legacy 'vn' spelling stored by older builds. */
export function normalizeLang(value: unknown): Lang {
  return value === "en" ? "en" : "vi";
}

/** The only key and event used for the language preference. */
export const LANG_STORAGE_KEY = "vnn:lang";
export const LANG_CHANGE_EVENT = "vnn:lang-change";

/**
 * The stored language, readable outside a React tree.
 *
 * It lives here rather than in the auth context because `app/lib/api.ts` needs
 * it to phrase network errors, and the context already imports the API client —
 * putting it there would close an import cycle.
 */
export function readStoredLang(): Lang {
  if (typeof window === "undefined") return "vi";
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === "en") return "en";
    if (saved === "vn" || saved === "vi") return "vi";
    if (localStorage.getItem("app-language") === "en") return "en";
  } catch {
    /* storage blocked */
  }
  return "vi";
}

